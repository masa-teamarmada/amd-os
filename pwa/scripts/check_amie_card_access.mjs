import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { compileFunction } from 'node:vm';
import { memberSurfacePermission } from '../src/lib/project-surface-permissions.ts';
const source=readFileSync(new URL('../src/lib/project-workspace.ts',import.meta.url),'utf8');
const start=source.indexOf('export function projectScopedPathAllowed(');
const end=source.indexOf('\nfunction emptyCategories',start);
assert.ok(start>=0&&end>start);
const fn=source.slice(start,end);
const allowed=compileFunction(fn.slice(fn.indexOf('{')+1,fn.lastIndexOf('}')),['access','pathname','memberSurfacePermission']);
const member={memberId:'fixture',isAdmin:false,scope:'project',projects:[{projectId:'p21'}],surfaceGrants:[]};
const design='11111111-1111-4111-8111-111111111111',asset='22222222-2222-4222-8222-222222222222';
const uri=p=>`/project/${p}/card-designs/${design}/assets/${asset}`;
assert.equal(allowed(member,uri('p21'),memberSurfacePermission),false,'workspace membership does not expose cards');
const viewer={...member,surfaceGrants:[{member_id:'fixture',project_id:'p21',surface:'cockpit',permission:'view'}]};
assert.equal(allowed(viewer,uri('p21'),memberSurfacePermission),true,'scoped cockpit reader can open own PDF');
assert.equal(allowed(viewer,uri('p00'),memberSurfacePermission),false,'foreign project stays blocked');
assert.equal(allowed(viewer,`/card-designs/${design}/assets/${asset}`,memberSurfacePermission),false,'global legacy URL stays outside scoped surface');
assert.equal(allowed(member,'/project/p21/workspace',memberSurfacePermission),true,'existing workspace route is unchanged');
assert.equal(allowed(viewer,'/admin/card-designs',memberSurfacePermission),false,'scoped reader cannot enter admin');
const page=readFileSync(new URL('../src/app/(app)/project/[projectId]/card-designs/[designId]/assets/[assetId]/page.tsx',import.meta.url),'utf8');
assert.match(page,/design\.owner_project_id !== projectId/,'page must verify URL owner against DB');
assert.match(page,/version\?\.design_id !== designId/,'asset version must belong to design');
assert.match(page,/amieCardCanRead\(member, asset\.project_id\)/,'asset project must also be readable');
console.log('card scoped viewer access: own grant allowed; workspace-only, foreign and admin denied; asset ownership verified');
