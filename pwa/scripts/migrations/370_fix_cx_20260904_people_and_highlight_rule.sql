個別の人では三人。**山本さん**は、NIMSの人事部長に相談したところ、クロスアポイントメントでNewCoと兼務するとNIMS内での昇進の可能性が絶たれると言われた。制度の条文としてそう定められているわけではなく、国研の運用の実体としてそうなっている。そのため正式な参画は難しい。ただし正式に関わることは必須ではない。しかも山本さんは、会社に所属していないどころか会社自体がまだ無い状態で、神谷さんのために毎晩遅くまで開発を進めている。この功労を「所属していないから」という理由で評価から外してはならない。山本さんの動機はFRC型の研究をやりたいことにあり、アカデミアに籍を置いたままCryoXの方向性とお金の使い方を決める裁量に関われるかが要点になる。役割名と受け口を用意し、名前が載っていない理由を戦略的な選択として先に整理しておく。役割の分担は夏目さんらと相談する。

**千徳さん**はCryoX参画がほぼ確定している。いまも名刺作成などを自主的に進め、休日も無報酬でNIMSへ来てNewCoの準備を手伝っている。仕事の精度が高く、クリエイティブな業務もこなせるため、設立後の中核として期待できる。

**小林さん**はNewCoへの所属を断固拒否している。国研に勤務しているというステータスを重視しているため。契約社員の5年上限で来年度から給与が無くなる状況で、報酬の一部からの参画を提案したが受け入れられていない。仕事の精度は高く、スケジュール管理にも向いているという評価なので、所属を前提にしない関わり方があるかは別途考える。

所属も報酬も無いメンバーが夜も休日も動いている、という状態そのものは、CEOに必要な巻き込み力の実績として見るべき事実である。投資家が問う「ビジネス側の経営能力」とは別の軸で、ここは評価に入れる。

事業の側では、期待値調整の話が出た。アカデミア向けに冷凍機を売る事業のキーサクセスファクターは、どこまでをサービスとして提供し、どこからはやらないかの線引きだという指摘が、Blueforsの関係者から出ていた。線引きをしないと何が起きるか。技術営業が顧客の研究室に張り付いたまま戻ってこず、次の案件を受けられない。顧客の要求は「これもやって、あれもやって」と積み上がる。納品後に不具合が出たとき、メーカー責任か研究者責任かの切り分けができず、装置の中身に入れたサンプルを全部出して検証する羽目になる。サービス範囲を文書で定義し、顧客と合意を取ることが必要になる。

資金と体制については、第2ラウンドまでの1年半から2年はいまのチーム・いまの色で進め、その間に明らかな進捗が出ている状態を作るという整理になった。マイルストーンはVC側では判断しきれない部分があるため、自分たちで置く。売れるものはもう作れるという認識はある一方、開発自体が思うように進んでいない部分もあり、VCの速度感と開発と人の気持ちが噛み合っていない状態にある。周辺情報として、大学発スタートアップは経産省の資料で東大発が最多、次いで京大が急伸しており、筑波大・NIMS発も出てきていることが共有された。

