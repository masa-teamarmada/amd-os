技術面で前回からの最大の差分は、超伝導線材の細線化だった。磁気冷凍は「非力だ」と言われるが、その原因は磁場の切り替え速度にあり、速くするには超伝導線の交流損失を下げる必要がある。高温超伝導体は工場から幅4mmのテープで供給され、機械加工では傷が入り、レーザーでは周囲まで溶けるため、細線化は業界共通の壁だった。山内さんが半導体の微細加工技術を応用してこれを解決し、先週その成果が形になった。神谷氏は「我々の分野の最新技術の10分の1の細さに相当する」と表現し、冷却パワーは2〜3倍になる見込みだと説明した。コイル化とADRへの実装はこれからの工程になる。

