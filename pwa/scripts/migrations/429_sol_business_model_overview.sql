2. **高く引き取れる液ほど、菌では処理しにくい。** 必要な菌体の量は金属の濃さに比例する。いまの取り込みの値（乾燥菌体1gあたり鉄0.053g、単回の試験値）では、金属5,000mg/Lの液1m³に乾燥菌体が約105kg要り、菌体の重さが液の1割を超える。特管の廃酸・廃アルカリは国が定めた方法（環境省の概要では中和、焼却、イオン交換設備等での再生）で処分するので、菌が働ける場面は中和の後になる
