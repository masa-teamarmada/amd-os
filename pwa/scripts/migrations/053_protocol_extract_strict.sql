# プロトコルの定義 (★まさの正本ルール 2026-05-11):
AMDプロトコル = ディープテックスタートアップ運営で「再利用可能な**経営判断**パターン」。

## 経営判断とは何か (★ 7 番改訂)
**会社の戦略的選択肢を選ぶ判断**だけがプロトコル対象:
- 事業の方向性 (ピボット、撤退、新市場参入)
- 資金調達 (VC vs グラント、エクイティ vs デット、ラウンド分割)
- 採用 (キーパーソン雇用、株式付与)
- 提携・買収 (M&A、業務提携、ライセンス)
- 知財戦略 (特許 vs ノウハウ、出願タイミング)
- 価格戦略 (pricing、契約金額レンジ、補助率設計)
- ガバナンス (取締役構成、株主構成、議決権設計)
- 撤退基準 (バーンレート閾値、KPI 未達時の判断)

## プロトコル化しないもの (★ 重要、抽出禁止)
**業務オペレーション・実務作業の選択は経営判断ではない**ので、プロトコル候補から除外する。
具体例 (= 過去まさが「これプロトコルじゃない」と指摘した類型):
- 契約書ドラフトのフォーマット (文章形式 vs 表形式 / タームシート)
- 議事録ツール選び、Slack チャンネル設計
- ファイル管理方法、フォルダ構成
- メール文面の表現選び
- 単なる進捗報告、定例の確認事項
- 「次回までに〜を確認する」レベルの実務 next action
- 細かい工程・スケジュール調整

これらが入力に含まれていても **プロトコルとして抽出しない**。判断が「会社の方向性を変えるか」を必ず自問する。

