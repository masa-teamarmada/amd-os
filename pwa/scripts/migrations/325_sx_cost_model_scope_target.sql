-- SX (p21) の想定系と成立ラインを埋める。
-- 総コスト目標300円/m³ は 2026-07-24 の SX 定例で置いた値 (既存処理コスト500円/m³前後に対して300円を狙う)。

BEGIN;
update project_cost_models set
  system_scope_md = $md$**対象** — 工場排液を、シアノバクテリア（藍藻）に吸着させて処理する。現在の試算ケースは色素分解。

**規模** — 顧客工場1拠点あたり 100 m³/日 × 300 日/年 ＝ 30,000 m³/年。1バッチ100 m³、反応時間（HRT）4時間のバッチ運転。

**方式は2つを並べて比較する**
- **A：循環カートリッジ方式** — 菌体をカートリッジ内の保持モジュールに留め、排液を循環させて接触させる。モジュールは耐用バッチ数ごとに交換する。
- **B：直接投入方式** — 菌体を槽へ直接投入して撹拌し、反応後に UF/MF 膜で菌体を分離回収する。膜は約3年で交換する。

**槽は既設／新設の2通り** — 顧客の既存調整タンクを流用できれば0円。新設ならコンクリート地下タンク100 m³で1,800万円（10年償却）。この掛け合わせで4シナリオになる。

**設備は独立プラント新設ではなく増分アドオン** — 顧客の既存調整タンク・排水ライン・ユーティリティ・主処理設備を使い、密閉接触・循環、菌体捕捉、回収サービスを足す（2026-07-23 確定）。

**菌体は中央培養拠点で作る** — 各現場では培養しない。培養設備は全顧客共通の共有資産として、供給拠点数で配賦する。現在の配賦先は1拠点＝1社で全量負担（最も保守的）。

**収益モデル** — 処理費のみ。売価500円/m³。回収物（金属など）の売却収入はまだモデルに入れていない。

**人件費の扱い** — 自動制御による無人運転を前提にして総コストへ算入していない。静脈側に人を張り付ける装置は売れないという判断（顧客側の運転管理アウトソース化ニーズはツムラヒアリングで確認済み）。ただし菌体の搬入・搬出やモジュール交換が消えるわけではなく、SX側の巡回サービス原価として立て直す必要がある（未計上）。参考値は下表に併記する。$md$,
  target_total_cost_per_m3 = 300,
  target_note = '2026-07-24 SX定例で置いた総コスト目標。既存処理コスト500円/m³前後に対して300円/m³を狙う。売価500円のままなら利益率40%に相当する。',
  unit_basis_label = 'm³',
  updated_at = now()
where cost_model_id = 'cm_p21_260820';
COMMIT;
