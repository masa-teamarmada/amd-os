### 反社会的勢力について

許可を持って行う廃液の中間処理は、設備投資が大きく、大手・上場企業が中心である。警察庁の最新の報告書（令和6年における組織犯罪の情勢）が、暴力団が進出・関与している事業として挙げるのは金融業・建設業・労働者派遣業・風俗営業等で、「産業廃棄物」という語は本文に出てこない。

